#!/usr/bin/env python3
"""Regenerate site FAQ data and Markdown from one source; --check detects drift."""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
source = ROOT / "data" / "faq.json"
data = json.loads(source.read_text(encoding="utf-8"))
questions = data["questions"]
ids = [entry["id"] for entry in questions]
if ids != list(range(1, 41)):
    raise SystemExit(f"Expected exactly FAQ ids 1–40; got {ids!r}")
if any(not all(entry.get(k) for k in ("q", "a", "group")) for entry in questions):
    raise SystemExit("A FAQ entry is incomplete")

js_text = "// GENERATED by scripts/build_faq.py; edit data/faq.json instead.\nwindow.lastLightFaq = " + json.dumps(data, ensure_ascii=False, indent=2) + ";\n"
md = [
    "# Last Light — economy FAQ",
    "",
    f"**Version {data['version']}.** {data['status']}. This file and the website FAQ are generated from `data/faq.json`.",
    "",
    "The current market rules live in [economy-v0.3.md](economy-v0.3.md); underlying colony rules and the original critical round sequence remain in [economy-v0.2.md](economy-v0.2.md).",
    "",
]
current_group = None
for entry in questions:
    if entry["group"] != current_group:
        current_group = entry["group"]
        md += [f"## {current_group}", ""]
    md += [f"### {entry['id']}. {entry['q']}", "", entry["a"], ""]
md_text = "\n".join(md)
outputs = [(ROOT / "site" / "faq-data.js", js_text), (ROOT / "docs" / "faq.md", md_text)]
if "--check" in sys.argv:
    stale = [str(path) for path, expected in outputs if not path.exists() or path.read_text(encoding="utf-8") != expected]
    site = (ROOT / "site" / "index.html").read_text(encoding="utf-8")
    spec = ROOT / "docs" / f"economy-v{data['version']}.md"
    if f"DESIGN / v{data['version']}" not in site or f"economy-v{data['version']}.md" not in site:
        stale.append("site/index.html (version or specification link)")
    if not spec.exists():
        stale.append(str(spec))
    if stale:
        raise SystemExit("Out of sync: " + ", ".join(stale) + "; run python scripts/build_faq.py and update site/spec")
    print("FAQ synchronized: 40 questions, website and Markdown match source/version")
else:
    for path, text in outputs:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    print("Generated site/faq-data.js and docs/faq.md from 40 FAQ entries")
